export const LANGS: Record<string, { name: string; dict: Dict; rtl?: boolean }> = {
  en: { name: 'English', dict: en }, fr: { name: 'Français', dict: fr }, es: { name: 'Español', dict: es },
  pt: { name: 'Português', dict: pt }, de: { name: 'Deutsch', dict: de }, it: { name: 'Italiano', dict: it },
  nl: { name: 'Nederlands', dict: nl }, pl: { name: 'Polski', dict: pl }, tr: { name: 'Türkçe', dict: tr },
  ru: { name: 'Русский', dict: ru }, ar: { name: 'العربية', dict: ar, rtl: true }, id: { name: 'Bahasa Indonesia', dict: id },
  ja: { name: '日本語', dict: ja }, ko: { name: '한국어', dict: ko }, zh: { name: '中文', dict: zh },
};

const KEY = 'gv-lang';

function detect(): string {
  try {
    const saved = localStorage.getItem(KEY);
    if (saved && LANGS[saved]) return saved;
  } catch { /* stockage indisponible (navigation privee) */ }
  for (const l of navigator.languages ?? [navigator.language]) {
    const base = l.toLowerCase().split('-')[0];
    if (LANGS[base]) return base;
  }
  return 'en';
}

let lang = detect();
export const t = (key: keyof Dict, vars: Record<string, string | number> = {}) =>
  LANGS[lang].dict[key].replace(/\{(\w+)\}/g, (_, k) => String(vars[k]));

// Applique la langue : [data-i18n] = texte, [data-i18n-html] = HTML (textes statiques de ce fichier uniquement)
export function applyLang(next = lang) {
  lang = next;
  try { localStorage.setItem(KEY, lang); } catch { /* idem */ }
  const root = document.documentElement;
  root.lang = lang;
  root.dir = LANGS[lang].rtl ? 'rtl' : 'ltr';
  document.querySelector('meta[name="description"]')?.setAttribute('content', t('desc'));
  document.querySelectorAll<HTMLElement>('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n as keyof Dict); });
  document.querySelectorAll<HTMLElement>('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.dataset.i18nHtml as keyof Dict); });
  document.querySelectorAll<HTMLElement>('[data-i18n-label]').forEach(el => el.setAttribute('aria-label', t(el.dataset.i18nLabel as keyof Dict)));
  document.body.dataset.dropText = t('drop');
}
